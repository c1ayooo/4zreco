const impactOrchestrationGuidance = `

【危害深度编排（代码内置）】
- 规划的单位不是“扫了什么”，而是“证明了什么危害”。高价值入口出现后，优先派“影响证明/数据面扩展/权限矩阵”意图，而不是继续铺新面。
- **拿到一个 critical 不是收敛信号**：隧道视野会让“爱上一条优雅链”吃掉其他机理完全不同的风险面（文件上传/任意写/方法枚举/sink 审计）。高价值成果进入影响证明的同时，必须至少保留 1 条并行意图推进其他攻击面，全部面收口前不写总结。
- 发现可读接口（未授权/越权/导出/列表/详情）后，必须派 1–2 条取数意图：同前缀兄弟端点、分页/时间窗/筛选取全量、导出接口优先；summary 写清目标端点族、取数量级、落盘与 save_evidence 要求。
- high/critical finding 如果 evidence 只有 L0/L1（版本、报错、单条样本），视为“未完成”：派一条影响证明意图，要求补齐原始请求/响应、≥10 条或全量数据、权限矩阵/写测试回读、不脱敏证据；补齐前不要把目标标 met。
- 覆盖矩阵除漏洞类外，必须覆盖三种危害面：① 读（能拿到多少数据、哪些敏感字段）② 写（自建测试对象能否写入并回读）③ 权限（匿名/低权/高权差异）。缺哪面补哪面。
- 验收标准里禁止只写“发现某漏洞”；写成“证明某身份可读取 N 条含 X 字段的数据 / 可写入测试对象并回读 / 可执行 id 命令”。
- 写测试只允许自建测试对象；派意图时把“测试对象命名、修改前后回读、清理”写进 summary，避免 worker 碰生产数据。
- 报告/证据不脱敏：第一方 SRC 需要原值；客户交付的脱敏版是单独产物，不要提前把原始证据打码。
- 拿不准“这样算不算证明充分”时，让执行侧按 skills/src-acceptance 的验收清单复核（已装配该 skill 就加载它）。
`

// srcReportAnnex 追加到 reporter 的报告纪律。
const srcReportAnnex = `

【SRC 全量证据附录（代码内置）】
报告不能只贴“关键片段”。在「证据」之后增加 ` + "`## 全量证据附录`" + `，按以下顺序写：
1. **原始请求/响应**：完整请求行、Host、Cookie/Authorization/token、请求体；完整响应状态、关键头、正文。HTTP 流量多时引用流量证据（baseline/proof）原文。
2. **数据集**：记录总数、字段清单、时间覆盖、样本（原值，不打码）；大数据集写 artifact:<id> + sha256，并说明文件位置。
3. **权限矩阵**：身份 × 接口 × 方法 × status/关键字段差异；越权类必须有两个以上身份。
4. **写测试**：测试对象 marker、修改前值、操作请求、回读值、清理结果；未执行写测试要明确写“仅验证能力面，未执行写操作”。
5. **复现命令**：可直接复制执行的 curl/sqlmap/nuclei/python 命令，注明预期输出特征。
6. **证据清单**：artifact:<id>/文件名/sha256、traffic id、验证时间、验证身份。
- **不脱敏**：目标数据保留原值；报告里的 ` + "`***`" + `、` + "`[redacted]`" + `、` + "`已脱敏`" + ` 会被 SRC 判为证据不足。客户脱敏版另行生成，不在本报告里做。
- 报告写完用 evidence_check（如有该工具）复核；缺核心项就在「未验证范围」写清缺什么、为什么，不要把未验证写成已确认。
`

